public class Variables{
    public static void main(String[] args) {
        int A = 10; // 32 bits i.e; 10 digits
        double B = 20.0000000000000000; //after decimal upto 17 digits
        char C = 'H';
        boolean D = true;
        String  E = "Harsha";
        float F = 60.0000000f; //after decimal upto 7 digits
        long G = 1234567890123456789L; // 64 bits i.e; 19 digits

        System.out.println(A);
        System.out.println(B);
        System.out.println(C);
        System.out.println(D);
        System.out.println(E);
        System.out.println(F);
        System.out.println(G);
    }
}
