public class Swap_Numbers_Third_Variable {
    public static void main(String[] args) {

        int a = 20;
        int b = 10;

        int c = a;
        a = b;
        b = c;

        System.out.println("c = " +c);
        System.out.println("a = " +a);
        System.out.println("b = " +b);

    }
}
